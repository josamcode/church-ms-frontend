/*
 * Availability "families" collapse the eight backend modes into four intuitive
 * choices plus a "restrict to specific times" toggle. The picker in the UI
 * works with families; we only translate to/from the backend enum when saving
 * or loading, so the wire format and slot-generation semantics stay identical.
 */
export const AVAILABILITY_FAMILIES = ['ALWAYS', 'DATE', 'DAYS', 'DATES'];

export function modeToFamily(mode) {
  switch (mode) {
    case 'ALWAYS':
      return 'ALWAYS';
    case 'DATE_RANGE':
    case 'DATE_TIME_RANGE':
      return 'DATE';
    case 'SPECIFIC_DAYS':
    case 'SPECIFIC_DAYS_TIME':
      return 'DAYS';
    case 'SPECIFIC_DATES':
    case 'SPECIFIC_DATES_TIME':
    case 'DATE_TIME':
      return 'DATES';
    default:
      return 'ALWAYS';
  }
}

export function familySupportsTime(family) {
  return ['DATE', 'DAYS', 'DATES'].includes(family);
}

export function composeMode(family, restrictTimes) {
  switch (family) {
    case 'DATE':
      return restrictTimes ? 'DATE_TIME_RANGE' : 'DATE_RANGE';
    case 'DAYS':
      return restrictTimes ? 'SPECIFIC_DAYS_TIME' : 'SPECIFIC_DAYS';
    case 'DATES':
      return restrictTimes ? 'SPECIFIC_DATES_TIME' : 'SPECIFIC_DATES';
    case 'ALWAYS':
    default:
      return 'ALWAYS';
  }
}

export function isBookableMode(mode) {
  return mode !== 'NONE';
}

export function modeHasTime(mode) {
  return ['DATE_TIME_RANGE', 'SPECIFIC_DAYS_TIME', 'SPECIFIC_DATES_TIME', 'DATE_TIME'].includes(mode);
}

export function modeUsesAvailabilityRules(mode) {
  return !['NONE', 'ALWAYS'].includes(mode);
}

// Modes where slots come from a start/end time window (interval + duration used).
export function modeUsesTimeRange(mode) {
  return ['DATE_TIME_RANGE', 'SPECIFIC_DAYS_TIME'].includes(mode);
}

export function modeUsesDateRange(mode) {
  return ['DATE_RANGE', 'DATE_TIME_RANGE'].includes(mode);
}

export function modeUsesSpecificDays(mode) {
  return ['SPECIFIC_DAYS', 'SPECIFIC_DAYS_TIME'].includes(mode);
}

export function modeUsesSpecificDates(mode) {
  return ['SPECIFIC_DATES', 'SPECIFIC_DATES_TIME'].includes(mode);
}

export function modeUsesExactTimes(mode) {
  return ['SPECIFIC_DATES_TIME', 'DATE_TIME'].includes(mode);
}

// Duration + slot interval only matter when times are generated from a window.
export function modeUsesDuration(mode) {
  return modeUsesTimeRange(mode);
}

export function availabilityLabel(mode, tf) {
  switch (mode) {
    case 'NONE':
      return tf('bookings.public.modes.none', 'No availability');
    case 'ALWAYS':
      return tf('bookings.public.modes.always', 'Always available');
    case 'DATE_RANGE':
      return tf('bookings.public.modes.dateRange', 'Within a date range');
    case 'DATE_TIME_RANGE':
      return tf('bookings.public.modes.dateTimeRange', 'Within a date and time range');
    case 'SPECIFIC_DAYS':
      return tf('bookings.public.modes.specificDays', 'Specific days');
    case 'SPECIFIC_DAYS_TIME':
      return tf('bookings.public.modes.specificDaysTime', 'Specific days and times');
    case 'SPECIFIC_DATES':
      return tf('bookings.public.modes.specificDates', 'Specific dates');
    case 'SPECIFIC_DATES_TIME':
    case 'DATE_TIME':
      return tf('bookings.public.modes.specificDatesTime', 'Specific dates and times');
    default:
      return mode;
  }
}

/* ── Field keys are generated by the system, never typed by the admin ──────── */

const FIELD_KEY_PATTERN = /^[a-zA-Z][a-zA-Z0-9_]*$/;

export function isValidFieldKey(key) {
  return typeof key === 'string' && key.length <= 60 && FIELD_KEY_PATTERN.test(key);
}

// Turn a human label (Arabic or English) into a safe ascii key fragment.
export function slugifyFieldKey(label) {
  const base = String(label || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .replace(/_{2,}/g, '_')
    .slice(0, 50);
  if (!base) return '';
  return /^[a-z]/.test(base) ? base : `field_${base}`;
}

/*
 * Produce a stable, unique, backend-valid key for every field.
 *  - Existing valid keys (edit mode) are preserved so saved bookings keep
 *    resolving their answers.
 *  - New fields are derived from their label, falling back to field_N when the
 *    label has no ascii characters (e.g. a purely Arabic label).
 *  - Collisions get a numeric suffix.
 */
export function buildFieldKeys(fields = []) {
  const used = new Set();
  return fields.map((field, index) => {
    let base = isValidFieldKey(field?.key)
      ? field.key
      : slugifyFieldKey(field?.label) || `field_${index + 1}`;
    base = base.slice(0, 55);

    let candidate = base;
    let suffix = 2;
    while (used.has(candidate)) {
      candidate = `${base}_${suffix}`;
      suffix += 1;
    }
    used.add(candidate);
    return candidate;
  });
}

// Select option values are internal identifiers too — the admin only types the
// visible label and we derive a stable, unique value for each option.
export function buildOptionValues(options = []) {
  const used = new Set();
  return options.map((option, index) => {
    let base = (option?.value && String(option.value).trim())
      || slugifyFieldKey(option?.label)
      || `option_${index + 1}`;
    base = base.slice(0, 110);

    let candidate = base;
    let suffix = 2;
    while (used.has(candidate)) {
      candidate = `${base}_${suffix}`;
      suffix += 1;
    }
    used.add(candidate);
    return candidate;
  });
}


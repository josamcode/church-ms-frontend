export function mapTypeToForm(type) {
  const exactDatesFromLegacy = Array.isArray(type.availabilityConfig?.exactDateTimes)
    ? type.availabilityConfig.exactDateTimes.reduce((acc, entry) => {
      const existing = acc.find((item) => item.date === entry.date);
      if (existing) {
        existing.exactTimes = [
          ...new Set([...(existing.exactTimes || []), entry.time || '']),
        ]
          .filter(Boolean)
          .sort();
        return acc;
      }

      acc.push({
        date: entry.date || '',
        startTime: '',
        endTime: '',
        exactTimes: entry.time ? [entry.time] : [],
      });
      return acc;
    }, [])
    : [];

  const specificDates = Array.isArray(type.availabilityConfig?.specificDates)
    ? type.availabilityConfig.specificDates.map((entry) => ({
      date: entry.date || '',
      startTime: entry.startTime || '',
      endTime: entry.endTime || '',
      exactTimes: Array.isArray(entry.exactTimes) ? entry.exactTimes : [],
    }))
    : [];

  const mergedSpecificDates = [...specificDates];
  exactDatesFromLegacy.forEach((entry) => {
    if (mergedSpecificDates.some((item) => item.date === entry.date)) return;
    mergedSpecificDates.push(entry);
  });

  return {
    id: type.id,
    name: type.name || '',
    description: type.description || '',
    instructions: type.instructions || '',
    isActive: type.isActive !== false,
    availabilityMode:
      type.availabilityMode === 'DATE_TIME'
        ? 'SPECIFIC_DATES_TIME'
        : (type.availabilityMode || 'NONE'),
    durationMinutes: type.durationMinutes || 30,
    slotIntervalMinutes: type.slotIntervalMinutes || 30,
    capacity: type.capacity || 1,
    bookingHorizonDays: type.bookingHorizonDays || 60,
    availabilityConfig: {
      timezone: type.availabilityConfig?.timezone || 'Africa/Cairo',
      timeRange: {
        startTime: type.availabilityConfig?.timeRange?.startTime || '09:00',
        endTime: type.availabilityConfig?.timeRange?.endTime || '17:00',
      },
      dateRange: {
        startDate: type.availabilityConfig?.dateRange?.startDate || '',
        endDate: type.availabilityConfig?.dateRange?.endDate || '',
      },
      specificDays: Array.isArray(type.availabilityConfig?.specificDays)
        ? type.availabilityConfig.specificDays
        : [],
      specificDates: mergedSpecificDates,
      exactDateTimes: [],
    },
    dynamicFields: Array.isArray(type.dynamicFields)
      ? type.dynamicFields.map((field) => ({
        key: field.key || '',
        label: field.label || '',
        type: field.type || 'text',
        required: Boolean(field.required),
        placeholder: field.placeholder || '',
        helpText: field.helpText || '',
        options: Array.isArray(field.options)
          ? field.options.map((option) => ({
            label: option.label || '',
            value: option.value || '',
          }))
          : [],
      }))
      : [],
  };
}

export function serializeTypeForm(form) {
  const mode = form.availabilityMode;
  const bookable = isBookableMode(mode);
  const usesWindow = modeUsesTimeRange(mode);
  const fieldKeys = buildFieldKeys(form.dynamicFields);

  return {
    name: form.name.trim(),
    description: form.description.trim() || null,
    instructions: form.instructions.trim() || null,
    isActive: Boolean(form.isActive),
    availabilityMode: mode,
    // Duration + interval only mean something when slots are generated from a
    // window; for every other mode we fall back to the backend defaults instead
    // of persisting numbers the admin never actually configured.
    durationMinutes: usesWindow ? (Number(form.durationMinutes) || 30) : 30,
    slotIntervalMinutes: usesWindow ? (Number(form.slotIntervalMinutes) || 30) : 30,
    capacity: bookable ? (Number(form.capacity) || 1) : 1,
    bookingHorizonDays: bookable ? (Number(form.bookingHorizonDays) || 60) : 60,
    availabilityConfig: {
      timezone: form.availabilityConfig.timezone || 'Africa/Cairo',
      timeRange: {
        startTime: usesWindow ? (form.availabilityConfig.timeRange.startTime || null) : null,
        endTime: usesWindow ? (form.availabilityConfig.timeRange.endTime || null) : null,
      },
      dateRange: {
        startDate: modeUsesDateRange(mode)
          ? (form.availabilityConfig.dateRange.startDate || null)
          : null,
        endDate: modeUsesDateRange(mode)
          ? (form.availabilityConfig.dateRange.endDate || null)
          : null,
      },
      specificDays: modeUsesSpecificDays(mode) ? form.availabilityConfig.specificDays : [],
      specificDates: modeUsesSpecificDates(mode)
        ? form.availabilityConfig.specificDates
          .filter((entry) => entry.date)
          .map((entry) => ({
            date: entry.date,
            startTime: null,
            endTime: null,
            exactTimes: modeUsesExactTimes(mode)
              ? (entry.exactTimes || []).filter(Boolean)
              : [],
          }))
        : [],
      exactDateTimes: [],
    },
    dynamicFields: form.dynamicFields.map((field, index) => ({
      key: fieldKeys[index],
      label: field.label.trim(),
      type: field.type,
      required: Boolean(field.required),
      placeholder: field.placeholder.trim() || null,
      helpText: field.helpText.trim() || null,
      options: field.type === 'select'
        ? (() => {
          const labelled = field.options.filter((option) => option.label.trim());
          const values = buildOptionValues(labelled);
          return labelled.map((option, optionIndex) => ({
            label: option.label.trim(),
            value: values[optionIndex],
          }));
        })()
        : [],
    })),
  };
}
